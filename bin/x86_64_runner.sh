set -e

#####################################################
#  @brief cli
#  @description
#       Test, Trace, and Debug emulation
#       for x86-64 Linux binaries and the test suite
#####################################################

# Default settings
MODE="run"
GDB_PORT="1234"
DOCKER_IMAGE="credence-x86_64"
CREDENCE_ROOT=$(realpath "$(dirname "$0")/..")

usage() {
    cat << EOF
Usage: $(basename "$0") [OPTIONS] <path-to-x86_64-binary> [binary args...]
       $(basename "$0") --suite

A test and debugging runner for x86-64 Linux binaries generated by Credence.

Options:
  -s, --suite        Build Credence and run the test suite with x86-64 code
                     generation in a Linux container (test/run-tests.sh)
  -g, --debug        Start a GDB server on port $GDB_PORT and pause execution
  -t, --trace        Trace raw Linux syscalls executed by the binary (strace)
  -p, --port PORT    Override GDB port (default: $GDB_PORT)
  -h, --help         Show this help message

Examples:
  $(basename "$0") --suite
  $(basename "$0") ./build/test_x86_64
  $(basename "$0") -t ./build/test_x86_64
  $(basename "$0") -g ./build/test_x86_64
EOF
    exit 1
}

# Parse options
POSITIONAL_ARGS=()
while [[ $# -gt 0 ]]; do
    case "$1" in
        -s|--suite)
            MODE="suite"
            shift
            ;;
        -g|--debug)
            MODE="debug"
            shift
            ;;
        -t|--trace)
            MODE="trace"
            shift
            ;;
        -p|--port)
            GDB_PORT="$2"
            shift 2
            ;;
        -h|--help)
            usage
            ;;
        *)
            POSITIONAL_ARGS+=("$1")
            shift
            ;;
    esac
done

set -- "${POSITIONAL_ARGS[@]}"

# Build the x86-64 image from Dockerfile.x86_64 once
if ! docker image inspect "$DOCKER_IMAGE" > /dev/null 2>&1; then
    echo ">>> Building $DOCKER_IMAGE from Dockerfile.x86_64"
    docker build --platform linux/amd64 -t "$DOCKER_IMAGE" \
        -f "$CREDENCE_ROOT/Dockerfile.x86_64" "$CREDENCE_ROOT"
fi

if [[ "$MODE" == "suite" ]]; then
    echo ">>> Running the x86-64 test suite in $DOCKER_IMAGE"
    # The source is copied without host build directories, and the CPM
    # cache and build directory are kept in volumes between runs
    docker run --rm \
        --platform linux/amd64 \
        -v "$CREDENCE_ROOT:/source:ro" \
        -v credence-x86_64-cpm:/root/.cache/CPM \
        -v credence-x86_64-build:/workspace/build \
        "$DOCKER_IMAGE" \
        bash -c '
            set -e
            tar -C /source --exclude="./build" --exclude="./build-*" \
                --exclude="./.cache" -cf - . | tar -C /workspace -xf -
            echo /workspace > "$HOME/.credence"
            cmake -B build -DCMAKE_BUILD_TYPE=Debug -DIWYU=OFF \
                -DCPM_SOURCE_CACHE=/root/.cache/CPM > /dev/null
            cmake --build build --parallel "$(nproc)"
            ./test/run-tests.sh -a x86_64 -d .
        '
    exit $?
fi

if [ $# -lt 1 ]; then
    echo "Error: Missing binary path."
    usage
fi

BINARY_PATH="$1"
shift # Remove binary path from args, leaving any args to pass to the binary

if [ ! -f "$BINARY_PATH" ]; then
    echo "Error: Binary '$BINARY_PATH' not found."
    exit 1
fi

# Get absolute path and directory info for mounting into Docker
ABS_BINARY_PATH=$(realpath "$BINARY_PATH")
BINARY_DIR=$(dirname "$ABS_BINARY_PATH")
BINARY_NAME=$(basename "$ABS_BINARY_PATH")

case "$MODE" in
    "run")
        echo ">>> Running x86-64 binary: $BINARY_NAME"
        set +e
        docker run --rm \
            -v "$BINARY_DIR:/workspace" \
            -w /workspace \
            --platform linux/amd64 \
            "$DOCKER_IMAGE" \
            "./$BINARY_NAME" "$@"

        EXIT_CODE=$?
        echo "==> Program exited with code: $EXIT_CODE"
        exit $EXIT_CODE
        ;;

    "trace")
        echo ">>> Running x86-64 binary with syscall tracing..."
        docker run --rm \
            --cap-add=SYS_PTRACE \
            -v "$BINARY_DIR:/workspace" \
            -w /workspace \
            --platform linux/amd64 \
            "$DOCKER_IMAGE" \
            strace "./$BINARY_NAME" "$@"
        ;;

    "debug")
        echo ">>> Starting GDB server for x86-64 binary on port $GDB_PORT..."
        echo ">>> In another terminal window, run:"
        echo ""
        echo "    gdb-multiarch \"$ABS_BINARY_PATH\" \\"
        echo "      -ex \"target remote localhost:$GDB_PORT\" \\"
        echo "      -ex \"layout asm\" \\"
        echo "      -ex \"layout regs\""
        echo ""
        echo "Waiting for GDB connection..."

        docker run --rm -it \
            --cap-add=SYS_PTRACE \
            -p "${GDB_PORT}:${GDB_PORT}" \
            -v "$BINARY_DIR:/workspace" \
            -w /workspace \
            --platform linux/amd64 \
            "$DOCKER_IMAGE" \
            gdbserver ":$GDB_PORT" "./$BINARY_NAME" "$@"
        ;;
esac
